"""Outbound links: extract, record and report. Offline, no network."""

import csv
import html
import re
from collections import defaultdict
from datetime import date
from urllib.parse import urldefrag, urlparse

SELF_DOMAINS = {"design.planning.data.gov.uk"}
HREF = re.compile(r'href="(https?://[^"]+)"')
LINK_KEYS = ("legislation", "specification")


def normalise(url):
    return urldefrag(html.unescape(url).strip())[0]


def domain(url):
    return (urlparse(url).hostname or "").lower()


def extract(pages):
    """Return {url: sorted source files} for every external link in the content."""
    found = defaultdict(set)
    for page in pages.values():
        urls = [normalise(u) for u in HREF.findall(str(page.html))]
        for key in LINK_KEYS:
            if key in page.meta:
                urls.append(page.meta[key]["url"])
        urls += [link["url"] for link in page.meta.get("useful_links", [])]
        for url in urls:
            url = normalise(url)
            if url.lower().startswith(("http://", "https://")):
                found[url].add(page.source)
    return {url: sorted(sources) for url, sources in sorted(found.items())}


def read_csv(path):
    try:
        with open(path, newline="", encoding="utf-8") as f:
            return list(csv.DictReader(f))
    except FileNotFoundError:
        return []


def write_csv(path, fields, rows):
    with open(path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fields, lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)


LINK_FIELDS = ["url", "domain", "first_seen"]


def sync(found, existing, today=None):
    """Rows for links.csv: keep first_seen for known links, add new ones, drop removed."""
    today = (today or date.today()).isoformat()
    seen = {row["url"]: row["first_seen"] for row in existing}
    return [
        {"url": url, "domain": domain(url), "first_seen": seen.get(url, today)}
        for url in found
    ]


def new_urls(found, existing):
    known = {row["url"] for row in existing}
    return [url for url in found if url not in known]


def allowed_domains(rows):
    return {row["domain"].lower() for row in rows}


def problems(found, allowed):
    """Unlisted domains and absolute links to this site."""
    out = []
    for url, sources in found.items():
        host = domain(url)
        where = ", ".join(sources)
        if re.search(r"\s", url):
            out.append(f"{where}: URL contains a space, encode it as %20 ({url!r})")
        elif host in SELF_DOMAINS:
            out.append(f"{where}: use a relative path instead of {url}")
        elif host not in allowed:
            out.append(f"{where}: domain {host} is not in links/domain.csv ({url})")
    return out


def report(found, allowed):
    """Markdown summary of linked domains."""
    by_domain = defaultdict(list)
    for url, sources in found.items():
        by_domain[domain(url)].append((url, sources))
    lines = [
        "# Linked domains",
        "",
        "Generated by `make links`. Do not edit.",
        "",
        "| Domain | Links | Listed | Example page |",
        "|---|---|---|---|",
    ]
    for host, items in sorted(by_domain.items(), key=lambda i: (-len(i[1]), i[0])):
        example = items[0][1][0].split("content/")[-1]
        listed = "yes" if host in allowed else "**no**"
        lines.append(f"| {host} | {len(items)} | {listed} | `{example}` |")
    return "\n".join(lines) + "\n"


LINKS_DIR = "links"


def stale(found, root):
    """Problems if the committed link files do not match the content."""
    out = []
    allowed = allowed_domains(read_csv(root / "domain.csv"))
    rows = read_csv(root / "links.csv")
    if [r["url"] for r in rows] != list(found):
        out.append("links/links.csv is out of date, run `make links`")
    try:
        current = (root / "domains.md").read_text(encoding="utf-8")
    except FileNotFoundError:
        current = ""
    if current != report(found, allowed):
        out.append("links/domains.md is out of date, run `make links`")
    return out


def main(argv):
    from pathlib import Path

    from application import ROOT
    from application.content import load_content

    root = ROOT / LINKS_DIR
    found = extract(load_content(ROOT / "content"))
    write_csv(
        root / "links.csv", LINK_FIELDS, sync(found, read_csv(root / "links.csv"))
    )
    allowed = allowed_domains(read_csv(root / "domain.csv"))
    Path(root / "domains.md").write_text(report(found, allowed), encoding="utf-8")
    for line in problems(found, allowed):
        print(line)
    print(f"{len(found)} links on {len({domain(u) for u in found})} domains")
    return 0


if __name__ == "__main__":
    import sys

    sys.exit(main(sys.argv[1:]))
